/** Word Insert ribbon: component types live in a floating popover, never a sidebar. */
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const ts=require('typescript');
const postcss=require('postcss');
const root=path.resolve(__dirname,'..');
const page=fs.readFileSync(path.join(root,'src/pages/CircuitEditorPage.tsx'),'utf8');
const css=fs.readFileSync(path.join(root,'src/index.css'),'utf8');
assert.equal(ts.createSourceFile('CircuitEditorPage.tsx',page,ts.ScriptTarget.Latest,true,ts.ScriptKind.TSX).parseDiagnostics.length,0,'editor TSX parses');
postcss.parse(css);
assert.doesNotMatch(page,/<aside id="editor-library-panel"/,'no left components sidebar');
assert.doesNotMatch(page,/editor-ribbon-library-toggle/,'no independent Components toggle');
const ribbon=page.slice(page.indexOf("{ribbonTab === 'insert' && <>"),page.indexOf("{ribbonTab === 'wiring' && <>"));
assert.match(ribbon,/aria-label="Insert component kinds"/);
for(const kind of ['Passive','Semiconductors','Logic ICs','Microcontrollers','Sensors','Output Devices']) assert.ok(page.includes(`'${kind}'`),`Ribbon kind configured: ${kind}`);
assert.match(ribbon,/RIBBON_INSERT_KINDS\.map\(kind =>/,'ribbon renders configured kinds');
assert.match(ribbon,/onClick=\{toggleMoreKinds\}/,'More kinds opens dropdown, not All Parts');
assert.match(page,/MORE_INSERT_KINDS\.map\(section =>/,'dropdown lists only remaining kinds');
assert.match(ribbon,/toggleInsertGallery\('circuits'\)/);
assert.match(ribbon,/toggleInsertGallery\('examples'\)/);
assert.match(ribbon,/aria-label="Breadboard size"/,'board size accessible from Insert');
const gallery=page.slice(page.indexOf('{paletteOpen && use3D && ribbonTab === \'insert\''),page.indexOf('</section>}',page.indexOf('{paletteOpen && use3D && ribbonTab === \'insert\'')));
assert.match(gallery,/role="dialog"/,'floating nonmodal gallery');
assert.match(gallery,/editor-insert-kind-list/,'all kinds are explicitly listed');
assert.match(gallery,/PALETTE.map\(section => <button/,'kind choices derive from real component catalog');
assert.match(gallery,/beginPaletteDrag\(event, item.tool, item.label, item\)/,'3D drag still uses original placement handler');
assert.match(gallery,/selectTool\(item.tool, item\);setPaletteOpen\(false\)/,'click selects part and closes gallery');
assert.match(page,/placePartAt\(tool, hole \?\? 'F12', undefined, benchPoint \?\? undefined\)/,'3D drop remains wired');
assert.match(page,/setRibbonTab\('wiring'\)[\s\S]*setPaletteOpen\(false\)/,'wiring mode does not open library');
assert.match(css,/\.editor-reference-ui \.editor-insert-gallery\s*\{[^}]*position:absolute/s,'gallery overlays workspace');
assert.match(css,/\.editor-reference-ui \.editor-insert-gallery \.editor-parts-grid/,'multiple components shown in gallery grid');
console.log('Insert gallery: category ribbon, floating searchable gallery, DnD, full-width workspace, examples, circuit and board controls: PASS');
